-- CREATE OR REPLACE TABLE LOAD_DATA.SILVER.TRIP_DATA
  
 SELECT (CONCAT(COLUMN_NAME,' ', DATA_TYPE, ',')) -- WITHIN GROUP (ORDER BY ORDINAL_POSITION)
  AS COLUMNS
  FROM INFORMATION_SCHEMA.COLUMNS
 WHERE TABLE_SCHEMA = 'SILVER' 
 AND TABLE_NAME = 'VIEW_TRIP_DATA'
 ORDER BY ORDINAL_POSITION
   ;

select * from SILVER.VIEW_TRIP_DATA;

create or replace TABLE LOAD_DATA.SILVER.TRIP_DATA
 (
TRIP_KEY INT IDENTITY(1,1) PRIMARY KEY,
PICKUP_DTTM TIMESTAMP_NTZ,
DROPOFF_DTTM TIMESTAMP_NTZ,
TRIP_DISTANCE_MILES FLOAT,
PASSENGER_COUNT NUMBER,
PICKUP_LOCATION_ID NUMBER,
DROPOFF_LOCATION_ID NUMBER,
PAYMENT_TYPE NUMBER,
FARE_AMOUNT FLOAT,
AIRPORT_RIDE_FLAG BOOLEAN,
MTA_TAX FLOAT,
TIP_AMOUNT FLOAT,
TOLLS_AMOUNT FLOAT,
TOTAL_AMOUNT FLOAT
); 


