// Use Staging Database to Load data 
CREATE  DATABASE IF NOT EXISTS LOAD_DATA;

-- Create Schema for Lake Nyc Taxi Dataset 
CREATE SCHEMA LAKE_NYC_TAXI_DS;

-- Create Stage for Lake Nyc Taxi Dataset 
CREATE STAGE STAGE_NTDS;



-- Role Based Access Management 
-- Creating separate roles and warehouses for each environment

CREATE ROLE IF NOT EXISTS DEV_READ;
CREATE ROLE IF NOT EXISTS DEV_WRITE;
CREATE ROLE IF NOT EXISTS DEV_OWNER;

CREATE ROLE IF NOT EXISTS TEST_READ;
CREATE ROLE IF NOT EXISTS TEST_WRITE;
CREATE ROLE IF NOT EXISTS TEST_OWNER;

CREATE ROLE IF NOT EXISTS PROD_READ;
CREATE ROLE IF NOT EXISTS PROD_WRITE;
CREATE ROLE IF NOT EXISTS PROD_OWNER;

CREATE WAREHOUSE IF NOT EXISTS DEV_WH
	WAREHOUSE_SIZE = 'XSMALL'
	AUTO_SUSPEND = 60
	AUTO_RESUME = TRUE
	INITIALLY_SUSPENDED = TRUE;

CREATE WAREHOUSE IF NOT EXISTS TEST_WH
	WAREHOUSE_SIZE = 'XSMALL'
	AUTO_SUSPEND = 60
	AUTO_RESUME = TRUE
	INITIALLY_SUSPENDED = TRUE;

CREATE WAREHOUSE IF NOT EXISTS PROD_WH
	WAREHOUSE_SIZE = 'XSMALL'
	AUTO_SUSPEND = 60
	AUTO_RESUME = TRUE
	INITIALLY_SUSPENDED = TRUE;

GRANT ROLE DEV_READ TO ROLE DEV_WRITE;
GRANT ROLE DEV_WRITE TO ROLE DEV_OWNER;
GRANT USAGE ON WAREHOUSE DEV_WH TO ROLE DEV_READ;

GRANT ROLE TEST_READ TO ROLE TEST_WRITE;
GRANT ROLE TEST_WRITE TO ROLE TEST_OWNER;
GRANT USAGE ON WAREHOUSE TEST_WH TO ROLE TEST_READ;

GRANT ROLE PROD_READ TO ROLE PROD_WRITE;
GRANT ROLE PROD_WRITE TO ROLE PROD_OWNER;
GRANT USAGE ON WAREHOUSE PROD_WH TO ROLE PROD_READ;

GRANT ROLE DEV_READ TO ROLE ACCOUNTADMIN;
GRANT ROLE DEV_WRITE TO ROLE ACCOUNTADMIN;
GRANT ROLE DEV_OWNER TO ROLE ACCOUNTADMIN;

GRANT ROLE TEST_READ TO ROLE ACCOUNTADMIN;
GRANT ROLE TEST_WRITE TO ROLE ACCOUNTADMIN;
GRANT ROLE TEST_OWNER TO ROLE ACCOUNTADMIN;

GRANT ROLE PROD_READ TO ROLE ACCOUNTADMIN;
GRANT ROLE PROD_WRITE TO ROLE ACCOUNTADMIN;
GRANT ROLE PROD_OWNER TO ROLE ACCOUNTADMIN;

